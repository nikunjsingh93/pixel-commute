const cache = {};
for (const k of Object.keys(G)) cache[k] = G[k].split(' ');

export const font = {
  measure(str, scale = 1) {
    return Math.max(0, [...String(str)].length * 4 - 1) * scale;
  },
  draw(g, str, x, y, scale = 1, color = '#fff') {
    g.fillStyle = color;
    let cx = x;
    for (const ch of String(str).toUpperCase()) {
      const r = cache[ch];
      if (r) {
        for (let j = 0; j < 5; j++)
          for (let i = 0; i < 3; i++)
            if (r[j][i] === '#') g.fillRect(cx + i * scale, y + j * scale, scale, scale);
      }
      cx += 4 * scale;
    }
    return cx - x;
  },
  // text with a dark drop shadow so it stays readable on any background
  shadow(g, str, x, y, scale = 1, color = '#fff', shadow = '#0c0f1a') {
    this.draw(g, str, x + scale, y + scale, scale, shadow);
    return this.draw(g, str, x, y, scale, color);
  },
};
